#!/usr/bin/env python3
"""Write css/team-colors.css from build/team-colors.json.

    python3 build/make_team_colors_css.py          # write
    python3 build/make_team_colors_css.py --check  # exit 1 if out of date

Every team's primary and accent as custom properties on [data-team="ABC"], so
a page can colour something in a team's own colours by setting the attribute
(team pages set it on <html>). The JSON is the one place team colours live;
make_team_theme.py reads the same file for the full team themes.
"""
import json, sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "build" / "team-colors.json"
OUT = REPO / "css" / "team-colors.css"

def render():
    colors = {k: v for k, v in json.loads(SRC.read_text()).items() if not k.startswith("_")}
    lines = ["/* GENERATED by build/make_team_colors_css.py from build/team-colors.json.",
             "   Don't edit by hand: change the JSON and re-run. */", ""]
    for abbr in sorted(colors):
        c = colors[abbr]
        lines.append(f'[data-team="{abbr}"] {{ --team-primary: {c["primary"]}; --team-accent: {c["accent"]}; }}')
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("css/team-colors.css is out of date; run build/make_team_colors_css.py")
            sys.exit(1)
        print("css/team-colors.css up to date")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(REPO)}")
