#!/usr/bin/env python3
"""Write css/team-colors.css and team-colors.js from build/team-colors.json.

    python3 build/make_team_colors_css.py          # write
    python3 build/make_team_colors_css.py --check  # exit 1 if out of date

Every team's primary, accent and chart colour as custom properties on
[data-team="ABC"], so a page can colour something in a team's own colours by
setting the attribute (team pages set it on <html>). team-colors.js carries
the same values as window.NBN_TEAM_COLORS for code that needs them as values:
a chart drawing SVG, a canvas. The JSON is the one place team colours live;
make_team_theme.py reads the same file for the full team themes.
"""
import json, sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "build" / "team-colors.json"
OUT = REPO / "css" / "team-colors.css"
OUT_JS = REPO / "team-colors.js"

def load():
    return {k: v for k, v in json.loads(SRC.read_text()).items() if not k.startswith("_")}

THEME_CSS = REPO / "css" / "theme.css"
DEFAULT_THEME = "nbn-today"
# The Mine callout's bar is a 3px mark: WCAG's non-text minimum against the page.
MINE_MIN_CONTRAST = 3.0

def _lum(hexc):
    c = [int(hexc[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]

def contrast(a, b):
    la, lb = _lum(a), _lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)

def theme_pages():
    """Each theme's --bg-page, from css/theme.css (:root is the default theme)."""
    import re
    css = THEME_CSS.read_text()
    out = {}
    for m in re.finditer(r'(:root(?:\[data-theme="([^"]+)"\])?)\s*\{(.*?)\n\}', css, re.S):
        page = re.search(r'--bg-page:\s*(#[0-9a-fA-F]{6})\b', m.group(3))
        if page:
            out[m.group(2) or DEFAULT_THEME] = page.group(1)
    return out

def mine_colors(colors):
    """{theme: {abbr: colour}}: the first of chart, accent, primary that clears
    MINE_MIN_CONTRAST on the theme's page, else whichever comes closest. Utah's
    navy chart colour vanishes on the dark page, so it takes its gold there."""
    out = {}
    for theme, page in theme_pages().items():
        out[theme] = {}
        for abbr, c in colors.items():
            cands = [c["chart"], c["accent"], c["primary"]]
            ok = [x for x in cands if contrast(x, page) >= MINE_MIN_CONTRAST]
            out[theme][abbr] = ok[0] if ok else max(cands, key=lambda x: contrast(x, page))
    return out

def render():
    colors = load()
    lines = ["/* GENERATED by build/make_team_colors_css.py from build/team-colors.json.",
             "   Don't edit by hand: change the JSON and re-run. */", ""]
    for abbr in sorted(colors):
        c = colors[abbr]
        lines.append(f'[data-team="{abbr}"] {{ --team-primary: {c["primary"]}; --team-accent: {c["accent"]}; --team-chart: {c["chart"]}; }}')
    # The signed-in member's team (my-team.js sets <html data-my-team>): the
    # colour of the Mine callout in css/components.css, chosen per theme by
    # mine_colors(): the first of chart, accent and primary that stands out
    # from that theme's page. Default theme first, then only the themes where
    # the pick differs.
    picks = mine_colors(colors)
    lines.append("")
    for abbr in sorted(colors):
        lines.append(f':root[data-my-team="{abbr}"] {{ --mine-c: {picks[DEFAULT_THEME][abbr]}; }}')
    for theme in sorted(picks):
        if theme == DEFAULT_THEME:
            continue
        for abbr in sorted(colors):
            if picks[theme][abbr] != picks[DEFAULT_THEME][abbr]:
                lines.append(f':root[data-theme="{theme}"][data-my-team="{abbr}"] {{ --mine-c: {picks[theme][abbr]}; }}')
    return "\n".join(lines) + "\n"

def render_js():
    colors = load()
    lines = ["// GENERATED by build/make_team_colors_css.py from build/team-colors.json.",
             "// Don't edit by hand: change the JSON and re-run. NBN_TEAM_COLORS.BOS.chart",
             "// is the colour a chart uses for Boston; primary and accent are the team's own.",
             "window.NBN_TEAM_COLORS = {"]
    for abbr in sorted(colors):
        c = colors[abbr]
        lines.append(f"  {abbr}: {{ primary: '{c['primary']}', accent: '{c['accent']}', chart: '{c['chart']}' }},")
    lines.append("};")
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    outputs = ((OUT, render()), (OUT_JS, render_js()))  # render() also reads css/theme.css
    if "--check" in sys.argv:
        stale = [p for p, text in outputs if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"{p.relative_to(REPO)} is out of date; run build/make_team_colors_css.py")
        # Every team's highlight must still stand out on every theme's page
        # (a new theme, or a changed team colour, could leave one with none).
        pages, picks = theme_pages(), mine_colors(load())
        faint = [f"{abbr} on {theme} ({contrast(c, pages[theme]):.2f}:1)"
                 for theme, by in picks.items() for abbr, c in by.items()
                 if contrast(c, pages[theme]) < MINE_MIN_CONTRAST]
        for f in faint:
            print(f"no team colour clears {MINE_MIN_CONTRAST}:1 for the Mine callout: {f}")
        if stale or faint:
            sys.exit(1)
        print("css/team-colors.css and team-colors.js up to date")
    else:
        for p, text in outputs:
            p.write_text(text)
            print(f"wrote {p.relative_to(REPO)}")
